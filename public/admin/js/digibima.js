document.addEventListener("DOMContentLoaded", function () {
  function handlePlaceholderAnimation(input, placeholder) {
    // Function to update placeholder based on input value
    function updatePlaceholder() {
      if (input.value.trim() !== "") {
        placeholder.classList.add("active");
      } else {
        placeholder.classList.remove("active");
      }
    }

    // Click event on placeholder
    placeholder.addEventListener("click", () => {
      input.focus();
    });

    // Focus and blur events on input
    input.addEventListener("focus", () => {
      placeholder.classList.add("active");
    });

    input.addEventListener("blur", () => {
      updatePlaceholder();
    });

    // Input event to handle value changes
    input.addEventListener("input", updatePlaceholder);

    // Initial check for value on page load
    updatePlaceholder();
  }

  // Select all input elements
  const inputs = document.querySelectorAll(".input, .input1");

  // Iterate over each input
  inputs.forEach((input) => {
    const placeholder = input.nextElementSibling; // Assuming placeholder is the next sibling element

    // Apply placeholder animation for current input
    handlePlaceholderAnimation(input, placeholder);
  });
});
document.addEventListener("DOMContentLoaded", function () {
  document.body.addEventListener("click", function (event) {
    const target = event.target;
    if (target.matches(".placeholder")) {
      const container = target.closest(".input-container");
      if (container) {
        const input = container.querySelector(".input");
        if (input) {
          input.focus();
          target.classList.add("active");
        }
      }
    }
  });

  document.body.addEventListener("focusin", function (event) {
    const target = event.target;
    if (target.matches(".input")) {
      const container = target.closest(".input-container");
      if (container) {
        const placeholder = container.querySelector(".placeholder");
        if (placeholder) {
          placeholder.classList.add("active");
        }
      }
    }
  });

  document.body.addEventListener("focusout", function (event) {
    const target = event.target;
    if (target.matches(".input")) {
      if (target.value === "") {
        const container = target.closest(".input-container");
        if (container) {
          const placeholder = container.querySelector(".placeholder");
          if (placeholder) {
            placeholder.classList.remove("active");
          }
        }
      }
    }
  });
});

function autoUppercase(input) {
  input.value = input.value.toUpperCase();
}

function registrNumbInput() {
  var regInputs = document.querySelectorAll(".registrnobInput");
  regInputs.forEach(function (input) {
    autoUppercase(input);
    const pattern = /^[A-Z0-9]{0,10}$/;
    let inputValue = input.value;
    if (!pattern.test(inputValue)) {
      input.value = inputValue.replace(/[^A-Z0-9]/g, "").substring(0, 10);
    }
  });
}


